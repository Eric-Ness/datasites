"""The certified-results importer: release records, the generated contract, collect/transform and a full run.

There is no 2026 contract yet (no data until states certify), so these tests run the importer exactly as
a 2026 contract will, against the 2024 files: the release record points at the 2024 election.
"""

from __future__ import annotations

import json
from datetime import date, datetime, timezone

import pytest
import yaml
from election_helpers import FakeContext, fixture_bytes, md_files

from datasites_core import fetch, publish
from datasites_core.contracts import parse_contract, site_contracts
from datasites_core.layout import blob_key, manifest_key, version_key
from datasites_core.store import get_json
from datasites_election import certified_2026
from datasites_election.adapters import ADAPTERS
from datasites_election.certified_2026 import Release

WA_URL = "https://results.vote.wa.gov/results/20241105/export/20241105_AllCounties.csv"
WA_2024 = Release("WA", election_date="2024-11-05", certified_at="2024-12-04", certification_url="https://www.sos.wa.gov/node/13114")
NOW = datetime(2026, 11, 20, 15, 37, tzinfo=timezone.utc)


def generated(state):
    return parse_contract("electiondata", yaml.safe_load(certified_2026.contract_yaml(state)), "generated")


def all_rows(store, doc):
    return json.loads(store.get(blob_key(doc["files"]["table/all.json"]["blob"]))[0])["rows"]


def test_releases_cover_every_adapter_and_nothing_is_certified_yet():
    assert set(certified_2026.RELEASES) == set(ADAPTERS) == {"WA", "MD"}
    for release in certified_2026.RELEASES.values():
        assert release.election_date == "2026-11-03"
        assert release.status == "unofficial" and release.certified_at is None
    # No 2026 contract exists until there is data: a dataset with nothing to publish would fail every run.
    assert not [c for c in site_contracts("electiondata") if c.id.startswith(certified_2026.DATASET_PREFIX)]


def test_release_records_are_checked():
    with pytest.raises(ValueError, match="before the election"):
        Release("WA", certified_at="2026-10-01", certification_url="https://example.org/")
    with pytest.raises(ValueError, match="certification_url"):
        Release("WA", certified_at="2026-12-03")
    with pytest.raises(ValueError, match="stage"):
        Release("WA", stage="PRIMARY")
    assert Release("WA", certified_at="2026-12-03", certification_url="https://example.org/").status == "certified"


def test_generated_contracts_are_valid_and_carry_the_states_terms():
    for state, adapter in ADAPTERS.items():
        contract = generated(state)
        assert contract.id == f"county-results-2026-{state.lower()}"
        assert contract.kind == "table" and contract.pipeline == "datasites_election.certified_2026"
        assert contract.columns == [*[c[0] for c in certified_2026.county_schema.COLUMNS], "status", "source_url", "certified_at"]
        assert list(contract.key) == certified_2026.county_schema.KEY
        assert contract.source.license == adapter.source.license
        assert contract.source.commercial_ok is adapter.source.commercial_ok
        assert contract.source.attribution == adapter.source.attribution
    assert generated("WA").source.commercial_ok is True
    assert generated("MD").source.commercial_ok is None  # no reuse terms on the Board's site
    text = certified_2026.contract_yaml("MD")
    assert text.startswith("# Generated by: uv run python -m datasites_election.certified_2026 contract MD\n")


def test_the_cli_prints_a_contract(capsys):
    assert certified_2026.main(["contract", "wa"]) == 0
    assert yaml.safe_load(capsys.readouterr().out)["id"] == "county-results-2026-wa"
    assert certified_2026.main(["contract", "zz"]) == 2


def test_collect_and_transform(monkeypatch):
    monkeypatch.setitem(certified_2026.RELEASES, "WA", WA_2024)
    ctx = FakeContext(generated("WA"), {WA_URL: fixture_bytes("wa_20241105_allcounties_excerpt.csv")})
    raw = certified_2026.collect(ctx)
    assert ctx.requests == [WA_URL]
    assert set(raw) == {"WA/AllCounties", "release"}
    assert json.loads(raw["release"])["resources"] == {"AllCounties": WA_URL}
    table = certified_2026.transform(raw)
    assert set(table["status"]) == {"certified"} and set(table["certified_at"]) == {"2024-12-04"}
    assert set(table["source_url"]) == {WA_URL}


def test_dataset_ids_name_the_release(monkeypatch):
    assert certified_2026.release_key("county-results-2026-md") == "MD"
    with pytest.raises(ValueError, match="no release 'NY'"):
        certified_2026.release_key("county-results-2026-ny")
    with pytest.raises(ValueError, match="are named"):
        certified_2026.release_key("senate-results")
    # A runoff is a release of its own, published as its own dataset.
    monkeypatch.setitem(certified_2026.RELEASES, "WA-RUNOFF", Release("WA", election_date="2026-12-01", stage="RUNOFF"))
    assert certified_2026.release_key("county-results-2026-wa-runoff") == "WA-RUNOFF"
    runoff = generated("WA-RUNOFF")
    assert runoff.id == "county-results-2026-wa-runoff" and runoff.title == "Washington 2026 runoff results by county"
    assert "December 1, 2026 runoff election" in runoff.description
    monkeypatch.setitem(certified_2026.RELEASES, "GA-RUNOFF", Release("GA", election_date="2026-12-01", stage="RUNOFF"))
    with pytest.raises(ValueError, match="no adapter for GA"):
        certified_2026.release_key("county-results-2026-ga-runoff")


def test_full_run_then_certification_republishes(store, monkeypatch):
    """Maryland 2024 through the engine: unofficial first, then recording the certification republishes."""
    contract = generated("MD")
    held = Release("MD", election_date="2024-11-05")
    urls = ADAPTERS["MD"].resources(date.fromisoformat(held.election_date))
    bodies = {urls[nn]: body for nn, body in md_files("md_pg24_county_results_excerpt.txt", line_endings="crlf").items()}
    monkeypatch.setattr(fetch.CollectContext, "get", lambda self, url, **kw: bodies[url])
    monkeypatch.setitem(certified_2026.RELEASES, "MD", held)

    first = publish.run_dataset(contract, store, now=NOW)
    assert first.outcome == "published", first.report.as_dict()
    doc, _ = get_json(store, version_key("electiondata", contract.id, first.version))
    assert doc["coverage"] == {"start": "2024", "end": "2024"}
    assert doc["source"]["commercial_ok"] is None and doc["key"] == certified_2026.county_schema.KEY
    assert {r["status"] for r in all_rows(store, doc)} == {"unofficial"}

    assert publish.run_dataset(contract, store, now=NOW.replace(day=21)).outcome == "unchanged"

    certified = Release(
        "MD",
        election_date="2024-11-05",
        certified_at="2024-12-05",
        certification_url="https://conduitstreet.mdcounties.org/2024/12/05/maryland-certifies-presidential-election-results/",
    )
    monkeypatch.setitem(certified_2026.RELEASES, "MD", certified)
    third = publish.run_dataset(contract, store, now=NOW.replace(day=22))
    assert third.outcome == "published" and third.version != first.version
    doc, _ = get_json(store, version_key("electiondata", contract.id, third.version))
    assert {(r["status"], r["certified_at"]) for r in all_rows(store, doc)} == {("certified", "2024-12-05")}
    manifest, _ = get_json(store, manifest_key("electiondata", contract.id))
    assert manifest["current"] == third.version and first.version in manifest["previous"]
