// Copies which visualizedata.org pages and indicators use each dataset into apps/web/src/lib/visualizedata.json,
// so every dataset page can link to the charts built from it. visualizedata.org records this in its own
// repository (src/data/site/sources.json, rebuilt with its data); it isn't published, so run this from a
// checkout beside this one after visualizedata.org changes, then commit the result:
//   node scripts/sync-visualizedata.mjs [path to visualizedata.org's sources.json]
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./verify/lib.mjs";

const from = process.argv[2] ?? join(ROOT, "..", "visualizedata.org", "src", "data", "site", "sources.json");
const doc = JSON.parse(readFileSync(from, "utf8"));
const sites = JSON.parse(readFileSync(join(ROOT, "packages", "registry", "src", "sites.json"), "utf8"));
const known = new Set(JSON.parse(readFileSync(join(ROOT, "packages", "registry", "src", "datasets.json"), "utf8")).map((d) => `${d.site}/${d.id}`));
const siteByDomain = new Map(sites.map((s) => [s.domain, s.id]));

const href = (path) => {
  if (!/^\/[a-z0-9/_-]*$/.test(path)) throw new Error(`unexpected visualizedata.org path ${JSON.stringify(path)}`);
  return path;
};
const datasets = {};
for (const { site: domain, datasets: list } of doc.sites) {
  const site = siteByDomain.get(domain);
  if (!site) throw new Error(`${from}: unknown site ${domain}`);
  for (const d of list) {
    const pages = (d.parts ?? []).map((p) => ({ label: p.label, href: href(p.href) }));
    const indicators = (d.indicators ?? []).map((i) => ({ label: i.name, href: href(i.href) }));
    if (!pages.length && !indicators.length) continue;
    const key = `${site}/${d.id}`;
    if (!known.has(key)) throw new Error(`${from}: ${key} is not in the registry`);
    datasets[key] = { pages, indicators };
  }
}
const out = {
  note: "Generated by scripts/sync-visualizedata.mjs from visualizedata.org's src/data/site/sources.json. Do not edit by hand.",
  generated_at: doc.generated_at,
  datasets: Object.fromEntries(Object.entries(datasets).sort(([a], [b]) => a.localeCompare(b))),
};
const target = join(ROOT, "apps", "web", "src", "lib", "visualizedata.json");
writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
const n = Object.values(datasets).reduce((a, d) => a + d.indicators.length, 0);
console.log(`wrote ${target}: ${Object.keys(datasets).length} datasets, ${n} indicators (visualizedata.org data of ${doc.generated_at})`);
